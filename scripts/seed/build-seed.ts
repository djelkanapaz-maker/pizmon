// Generates supabase/seed.sql from scripts/seed/catalog.ts and the questionnaire template.
//   npx tsx scripts/seed/build-seed.ts
// The output is idempotent (deterministic ids + ON CONFLICT) and safe to re-run.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { readFileSync } from 'node:fs';
import { COMPANY, GENRES, CATEGORIES, MOODS, MOMENTS, TRACKS, SPECIALTIES, CONTENT, EDITORIAL_PLAYLISTS } from './catalog';

type RosterEntry = { name: string; bio: string; social: Record<string, string> };
const ROSTER = JSON.parse(readFileSync(join(import.meta.dirname, 'atisuto/roster.json'), 'utf8')) as { roster: RosterEntry[]; live: (Omit<RosterEntry, 'name'>)[] };
const slugOf = (n: string) => n.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const DJS = [
  ...ROSTER.roster.map((r) => ({ ...r, kind: 'dj' as const })),
  ...ROSTER.live.map((r) => ({ ...r, name: 'EILON HAZAN', kind: 'live' as const })),
];
import { definitionV1 } from '../../src/core/questionnaire/definition-v1';

const q = (s: string | null | undefined) => (s === null || s === undefined ? 'null' : `'${s.replace(/'/g, "''")}'`);
const arr = (xs: readonly string[]) => `array[${xs.map(q).join(',')}]::text[]`;
const C = q(COMPANY.id);
const id = (ns: string, key: string) => `md5(${q(`${COMPANY.id}:${ns}:${key}`)})::uuid`;

const out: string[] = [];
out.push(`-- GENERATED by scripts/seed/build-seed.ts — do not edit by hand.
-- DEVELOPMENT / DEMO CONTENT. Rows are flagged is_demo where the table supports it.
begin;
insert into public.companies (id, slug, brand_name, brand_tagline_he, brand_tagline_en)
values (${C}, ${q(COMPANY.slug)}, ${q(COMPANY.brand_name)}, ${q(COMPANY.brand_tagline_he)}, ${q(COMPANY.brand_tagline_en)})
on conflict (id) do nothing;`);

GENRES.forEach(([slug, he, en], i) =>
  out.push(`insert into public.genres (id, company_id, slug, name_he, name_en, sort_order) values (${id('genre', slug)}, ${C}, ${q(slug)}, ${q(he)}, ${q(en)}, ${i}) on conflict do nothing;`));
CATEGORIES.forEach(([slug, he, en], i) =>
  out.push(`insert into public.tags (id, company_id, kind, slug, name_he, name_en, sort_order) values (${id('category', slug)}, ${C}, 'category', ${q(slug)}, ${q(he)}, ${q(en)}, ${i}) on conflict do nothing;`));
MOODS.forEach(([slug, he, en], i) =>
  out.push(`insert into public.tags (id, company_id, kind, slug, name_he, name_en, sort_order) values (${id('mood', slug)}, ${C}, 'mood', ${q(slug)}, ${q(he)}, ${q(en)}, ${i}) on conflict do nothing;`));
MOMENTS.forEach((m, i) =>
  out.push(`insert into public.wedding_moments (id, company_id, slug, name_he, name_en, description_he, description_en, sort_order, is_required, has_language_collections)
values (${id('moment', m.slug)}, ${C}, ${q(m.slug)}, ${q(m.he)}, ${q(m.en)}, ${q(m.dhe)}, ${q(m.den)}, ${i}, ${m.required}, ${!!m.lang}) on conflict do nothing;`));

const artists = [...new Set(TRACKS.map((t) => t.artist))];
artists.forEach((a) => out.push(`insert into public.artists (id, company_id, name) values (${id('artist', a)}, ${C}, ${q(a)}) on conflict do nothing;`));

TRACKS.forEach((t) => {
  const tid = id('track', `${t.title}|${t.artist}`);
  out.push(`insert into public.music_tracks (id, company_id, title, artist_id, genre_id, energy, language, decade, rights_status, rights_notes, status, is_demo)
values (${tid}, ${C}, ${q(t.title)}, ${id('artist', t.artist)}, ${id('genre', t.genre)}, ${t.energy}, ${q(t.lang)}, ${t.decade ?? 'null'}, 'metadata_only', 'Demo catalog entry: metadata only, no playback rights.', 'published', true) on conflict do nothing;`);
  for (const c of t.cats ?? []) out.push(`insert into public.track_tags (track_id, tag_id) values (${tid}, ${id('category', c)}) on conflict do nothing;`);
  for (const m of t.moods ?? []) out.push(`insert into public.track_tags (track_id, tag_id) values (${tid}, ${id('mood', m)}) on conflict do nothing;`);
  (t.moments ?? []).forEach((m, i) => {
    const [slug, col] = Array.isArray(m) ? m : [m, null];
    out.push(`insert into public.moment_tracks (moment_id, track_id, collection, sort_order) values (${id('moment', slug)}, ${tid}, ${q(col)}, ${i}) on conflict do nothing;`);
  });
});

DJS.forEach((d, i) => {
  const slug = slugOf(d.name);
  const links = Object.fromEntries(Object.entries(d.social).filter(([, v]) => v));
  const display = d.name === d.name.toUpperCase() ? d.name.toLowerCase().replace(/(^|[\s-])\p{L}/gu, (c) => c.toUpperCase()) : d.name;
  out.push(`insert into public.djs (id, company_id, display_name, slug, bio_en, specialties, photo_url, logo_url, links, kind, accepts_new_couples, sort_order, is_demo)
values (${id('dj', slug)}, ${C}, ${q(display)}, ${q(slug)}, ${q(d.bio)}, ${arr(SPECIALTIES[d.name] ?? [])}, ${q(`/djs/${slug}.webp`)}, ${q(`/djs/${slug}-logo.svg`)}, ${q(JSON.stringify(links))}::jsonb, ${q(d.kind)}, ${d.kind === 'dj'}, ${i}, false)
on conflict (company_id, slug) do update set display_name = excluded.display_name, bio_en = excluded.bio_en, photo_url = excluded.photo_url, logo_url = excluded.logo_url, links = excluded.links, kind = excluded.kind;`);
});

CONTENT.forEach((c) =>
  out.push(`insert into public.content_items (id, company_id, kind, title, description, creator_dj_id, media_url, genre_tags, status, is_featured, is_demo, published_at)
values (${id('content', c.title)}, ${C}, ${q(c.kind)}, ${q(c.title)}, 'Original placeholder audio generated for development.', ${c.dj ? id('dj', c.dj) : 'null'}, ${q(c.file)}, ${arr(c.tags)}, 'published', ${c.featured}, true, now()) on conflict do nothing;`));

EDITORIAL_PLAYLISTS.forEach((p) => {
  const pid = id('playlist', p.title_en);
  out.push(`insert into public.playlists (id, company_id, kind, title, description, purpose, status, is_featured)
values (${pid}, ${C}, 'editorial', ${q(p.title)}, ${q(p.title_en)}, ${q(p.purpose)}, 'published', ${p.featured}) on conflict do nothing;`);
  p.tracks.forEach((title, i) => {
    const t = TRACKS.find((x) => x.title === title);
    if (!t) throw new Error(`playlist track not in catalog: ${title}`);
    out.push(`insert into public.playlist_tracks (playlist_id, track_id, position, status) values (${pid}, ${id('track', `${t.title}|${t.artist}`)}, ${i}, 'confirmed') on conflict do nothing;`);
  });
});

out.push(`insert into public.radio_stations (id, company_id, name, description, mode, stream_url)
values (${id('radio', 'main')}, ${C}, 'Club Radio', 'Demo mode: an original looping placeholder, not a live broadcast. Configure a stream URL in Admin → Radio.', 'demo', '/demo-audio/golden-hour.mp3') on conflict do nothing;
insert into public.radio_schedule_items (id, station_id, title, description, host_dj_id, starts_at, ends_at) values
 (${id('show', '1')}, ${id('radio', 'main')}, 'Golden Hour (Demo show)', 'Warm reception grooves', null, date_trunc('day', now()) + interval '1 day 18 hours', date_trunc('day', now()) + interval '1 day 20 hours'),
 (${id('show', '2')}, ${id('radio', 'main')}, 'Mizrahi Nights (Demo show)', 'Israeli party classics', null, date_trunc('day', now()) + interval '2 days 20 hours', date_trunc('day', now()) + interval '2 days 22 hours'),
 (${id('show', '3')}, ${id('radio', 'main')}, 'Ceremony Lab (Demo show)', 'Entrances, strings and first dances', null, date_trunc('day', now()) + interval '4 days 19 hours', date_trunc('day', now()) + interval '4 days 20 hours')
on conflict do nothing;`);

out.push(`insert into public.questionnaires (id, company_id, name) values (${id('questionnaire', 'main')}, ${C}, 'Wedding music questionnaire') on conflict do nothing;
insert into public.questionnaire_versions (id, questionnaire_id, version, definition, published_at)
values (${id('qversion', '1')}, ${id('questionnaire', 'main')}, 1, $json$${JSON.stringify(definitionV1)}$json$::jsonb, now()) on conflict do nothing;
commit;`);

writeFileSync(join(import.meta.dirname, '../../supabase/seed.sql'), out.join('\n') + '\n');
console.log(`seed.sql written: ${TRACKS.length} tracks, ${artists.length} artists, ${DJS.length} Atisuto artists`);
